/** Locale of the page being rendered (Starlight route; `Astro.currentLocale` agrees but is not set for every route kind). */
export function pageLocale(astro: { locals: { starlightRoute?: { locale?: string } } }): Locale {
	const route = astro.locals.starlightRoute;
	if (!route) throw new Error('i18n: pageLocale() needs a Starlight route (render inside StarlightPage or a docs page)');
	return fromStarlight(route.locale);
}

/** Namespace (`vramcalc` of `vramcalc.title`) -> its keys, built once. */
const KEYS_BY_NS = Object.keys(en).reduce((m, k) => {
	const ns = k.slice(0, k.indexOf('.'));
	m.set(ns, [...(m.get(ns) ?? []), k as UiKey]);
	return m;
}, new Map<string, UiKey[]>());

/**
 * Every string of the namespaces `ns` in one locale: the browser slice a widget ships (UiStrings.astro). Throws on an
 * unknown namespace so a typo in a widget's `ns` list fails the build.
 */
export function slice(locale: Locale, ns: readonly string[]): Record<string, string> {
	const strings = DICT[asLocale(locale)];
	const out: Record<string, string> = {};
	for (const n of ns) {
		const keys = KEYS_BY_NS.get(n);
		if (!keys) throw new Error(`i18n: unknown namespace "${n}" (known: ${[...KEYS_BY_NS.keys()].join(', ')})`);
		for (const k of keys) out[k] = strings[k];
	}
	return out;
}
