// Bundle budget check (plan Task 11, Ruling O in AGENTS.md). Run after `bun run build`: `bun run size`.
//
// Every JS chunk in dist/_astro is measured gzipped (Bun.gzipSync, default level) and classified by its content,
// not its name, because Vite's chunk names follow whatever component happened to import a module first:
//   renderer  - the chunk that carries three.js (contains `WebGLRenderer`): <= 300,000 B each;
//   lazy map  - the elk layout worker and the xyflow map implementation, loaded only on pages with a map and only
//               when it scrolls into view: <= 600,000 B for the group together;
//   other     - every other chunk: <= 100,000 B each.
// Pagefind's files (dist/pagefind) are generated by the search indexer, not by our bundle, and are not counted.
// Exit code 1 on any violation, so CI fails on a budget regression.
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = join(import.meta.dir, '..');
const ASSETS = join(ROOT, 'dist', '_astro');

export const BUDGET = { renderer: 300_000, lazyMap: 600_000, other: 100_000 } as const;
export type Kind = 'renderer' | 'lazy-map' | 'other';

/** Classify a chunk by what it contains; see the header for why names are not used. */
export function classify(name: string, code: Buffer): Kind {
	if (code.includes('WebGLRenderer')) return 'renderer';
	// The elk worker is a separate entry whose name starts with "elk" (matching anywhere would also hit content hashes
	// such as "BEuP7Elk"); xyflow is recognised by its CSS class prefix.
	if (/^elk[.-]/i.test(name) || code.includes('react-flow__')) return 'lazy-map';
	return 'other';
}

function walk(dir: string): string[] {
	return readdirSync(dir).flatMap((n) => {
		const p = join(dir, n);
		return statSync(p).isDirectory() ? walk(p) : [p];
	});
}

function main(): number {
	if (!existsSync(ASSETS)) {
		console.error(`size-report: ${relative(ROOT, ASSETS)} not found, run \`bun run build\` first`);
		return 1;
	}
	const rows = walk(ASSETS)
		.filter((f) => f.endsWith('.js'))
		.map((f) => {
			const code = readFileSync(f);
			const name = relative(ASSETS, f).replace(/\\/g, '/');
			return { name, gz: Bun.gzipSync(code).length, kind: classify(name, code) };
		})
		.sort((a, b) => b.gz - a.gz);

	const fails: string[] = [];
	for (const r of rows) {
		if (r.kind === 'renderer' && r.gz > BUDGET.renderer) fails.push(`renderer ${r.name}: ${r.gz} > ${BUDGET.renderer}`);
		if (r.kind === 'other' && r.gz > BUDGET.other) fails.push(`chunk ${r.name}: ${r.gz} > ${BUDGET.other}`);
	}
	const lazy = rows.filter((r) => r.kind === 'lazy-map');
	const lazyTotal = lazy.reduce((s, r) => s + r.gz, 0);
	if (lazyTotal > BUDGET.lazyMap) fails.push(`lazy map group: ${lazyTotal} > ${BUDGET.lazyMap}`);

	const limit = (k: Kind) => (k === 'renderer' ? BUDGET.renderer : k === 'other' ? BUDGET.other : BUDGET.lazyMap);
	console.log('gzip B   budget    kind      chunk');
	for (const r of rows.filter((r) => r.kind !== 'other' || r.gz >= 10_000)) {
		console.log(`${String(r.gz).padStart(7)}  ${String(limit(r.kind)).padStart(7)}  ${r.kind.padEnd(8)}  ${r.name}`);
	}
	const small = rows.filter((r) => r.kind === 'other' && r.gz < 10_000).length;
	console.log(`(+${small} chunks under 10,000 B) lazy map group total: ${lazyTotal} / ${BUDGET.lazyMap}`);

	if (fails.length) {
		console.error(`\nsize-report: ${fails.length} budget violation(s)\n  ${fails.join('\n  ')}`);
		return 1;
	}
	console.log('size-report: all chunks within budget');
	return 0;
}

if (import.meta.main) process.exit(main());
